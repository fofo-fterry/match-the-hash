"""Shared setup for the Farm Stand tests. Please don't edit this file.

- Makes `import farmstand` find challenge-2/farmstand.py.
- Provides the `seal` fixture used by test_sealed.py.
- Prints your progress at the end of every run and, once every test passes,
  the passphrase.

The passphrase is encrypted with a key built from your app's answers in the
sealed tests, so it can only be unlocked by an app that follows the spec.
"""
