_unlocked = {}


def derive_key(texts):
    """Key = SHA-256 over every sealed answer, in name order."""
    material = "\n".join(texts[name] for name in sorted(texts))
    return hashlib.sha256(b"farmstand-v1\n" + material.encode("utf-8")).digest()


def xor_stream(key, data):
    stream = b""
    counter = 0
    while len(stream) < len(data):
        stream += hashlib.sha256(key + counter.to_bytes(4, "big")).digest()
        counter += 1
    return bytes(a ^ b for a, b in zip(data, stream))


def unseal(texts):
    key = derive_key(texts)
    plain = xor_stream(key, bytes.fromhex(PASSPHRASE_CIPHERTEXT))
    if hashlib.sha256(key + plain).hexdigest() != PASSPHRASE_TAG:
        return None
    return plain.decode("utf-8")


@pytest.fixture
def seal():
    def _seal(name, text, hint):
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        if digest != SEALED_DIGESTS.get(name):
            preview = text if len(text) <= 1500 else text[:1500] + " ...(truncated)"
            pytest.fail(
                f"Sealed check '{name}' doesn't match the right answers.\n"
                f"Reread {hint}. The visible tests in the other files are the "
                f"easiest place to debug.\n\nYour app produced:\n{preview}",
                pytrace=False,
            )
        _unlocked[name] = text

    return _seal


def pytest_report_header(config):
    try:
        import farmstand
    except Exception as exc:  # show *why* it won't import
        return (f"farmstand: NOT IMPORTABLE ({type(exc).__name__}: {exc}). "
                f"Create {CHALLENGE_DIR / 'farmstand.py'}")
    return f"farmstand: {getattr(farmstand, '__file__', farmstand)}"


def pytest_terminal_summary(terminalreporter, exitstatus, config):
    stats = terminalreporter.stats
    passed = sum(1 for r in stats.get("passed", []) if getattr(r, "when", "call") == "call")
    problems = len(stats.get("failed", [])) + len(stats.get("error", []))
    write = terminalreporter.write_line

    terminalreporter.write_sep("=", "FARM STAND")
    all_green = problems == 0 and passed >= EXPECTED_TESTS
    if all_green and set(_unlocked) == set(SEALED_DIGESTS):
        phrase = unseal(_unlocked)
        if phrase is None:
            write("Every test passed, but the sealed answers don't unlock the passphrase.")
            write("Were the tests changed? Restore the original tests/ folder and run again.")
            return
        bar = "*" * 56
        write(bar, bold=True, green=True)
        write(f"  ALL {EXPECTED_TESTS} TESTS PASS. THE FARM STAND IS OPEN!", bold=True, green=True)
        write("", green=True)
        write(f"  Passphrase:  {phrase}", bold=True, green=True)
        write("", green=True)
        write("  Say it out loud to your team. No typing it into chat!", green=True)
        write(bar, bold=True, green=True)
    elif problems == 0 and passed < EXPECTED_TESTS:
        write(f"{passed}/{EXPECTED_TESTS} tests passing. Passphrase still locked.")
        write("Looks like you ran only part of the suite. Run `python -m pytest` "
              "from challenge-2/ to unlock.")
    else:
        write(f"{passed}/{EXPECTED_TESTS} tests passing. Passphrase still locked.")
